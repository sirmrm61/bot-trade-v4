/**
 * Auto-generate scalping strategies from the market scanner.
 *
 *   1. rankPairs() — the same scan the user sees in /scalping (score = liquidity,
 *      spread, depth, slippage, volatility, round-trip cost).
 *   2. Top-ranked pairs are deduplicated per base asset and against the user's
 *      existing strategies (same exchange+symbol → skipped).
 *   3. For each candidate, candidate timeframes are evaluated on real candles:
 *      mean per-candle move vs the scanner's round-trip cost estimate. A pair is
 *      dropped when no timeframe moves enough to cover trading costs.
 *   4. A strategy is created per surviving pair via createStrategy()
 *      (same validation as manual creation), risk params derived from measured
 *      volatility and cost.
 *
 * Modes: "SCALP" creates SIGNAL strategies only. "COMBINED" additionally swaps
 * the extremes of the picked set for symbolic engines — the most volatile pick
 * becomes an ATM_SME momentum strategy and the least volatile becomes an
 * RMM_BSE channel-breakout strategy, both with smart (self-learning) mode on.
 *
 * The scan is the heavyweight step (~seconds, cached ~45s). Per-pair candle
 * evaluation is bounded by MAX_EVALUATED so the request stays under a minute.
 */

export type AutoGenMode = "SCALP" | "COMBINED";

const TF_CANDIDATES = ["5m", "15m", "30m", "1h"] as const;
const CANDLE_TARGET = 250;
const MIN_CANDLES = 100;
const MIN_EDGE = 0.5;         // mean candle move must cover ≥ half the round-trip cost
const MAX_EVALUATED = 15;     // bound the work when many top pairs get skipped
const FUTURES_LEVERAGE = 2;   // conservative default for perpetual picks
const DEFAULT_COST_PCT = 0.7; // fallback round-trip cost when metrics are missing

export interface AutoGeneratedStrategy {
  id: string;
  name: string;
  symbol: string;
  exchange: string;
  market: string;
  timeframe: string;
  kind: string;
  score: number | null;
}

export interface AutoGenerateResult {
  created: AutoGeneratedStrategy[];
  skipped: { symbol: string; exchange: string; reason: string }[];
  scanned: number;
  ranked: number;
}

interface TfEval {
  tf: string;
  movePct: number;
  edge: number;
  candles: number;
}

async function evalTimeframes(p: PairRank, costPct: number): Promise<TfEval | null> {
  const end = new Date();
  const evals = await Promise.all(
    TF_CANDIDATES.map(async (tf): Promise<TfEval | null> => {
      const start = new Date(end.getTime() - CANDLE_TARGET * tfMs(tf));
      const candles = await getCandles({
        symbol: p.symbol, timeframe: tf, start, end, exchange: p.exchange,
      }).catch(() => []);
      if (candles.length < MIN_CANDLES) return null;
      let sum = 0, n = 0;
      for (let i = 1; i < candles.length; i++) {
        const a = candles[i - 1].close, b = candles[i].close;
        if (a > 0 && b > 0) { sum += Math.abs(Math.log(b / a)); n++; }
      }
      const movePct = (sum / Math.max(n, 1)) * 100;
      return { tf, movePct, edge: movePct / Math.max(costPct, 0.05), candles: candles.length };
    }),
  );
  const ok = evals.filter((e): e is TfEval => e !== null && e.edge >= MIN_EDGE);
  // bigger edge wins; equal edge prefers the shorter timeframe (more trades)
  ok.sort((a, b) => b.edge - a.edge || TF_CANDIDATES.indexOf(a.tf as never) - TF_CANDIDATES.indexOf(b.tf as never));
  return ok[0] ?? null;
}

function defaultIndicators(): StrategyIndicatorConfig[] {
  return INDICATORS.map((d) => ({
    name: d.key,
    enabled: d.defaultEnabled,
    weight: d.scoring ? d.defaultWeight : 0,
    parameters: d.defaultParams,
    buyCondition: d.defaultBuyCondition as Condition | undefined,
    sellCondition: d.defaultSellCondition as Condition | undefined,
  }));
}

type AssignedKind = "SIGNAL" | "ATM_SME" | "RMM_BSE";

const KIND_NAME: Record<AssignedKind, string> = {
  SIGNAL: "اسکالپ",
  ATM_SME: "مومنتوم",
  RMM_BSE: "شکست کانال",
};

function buildInput(p: PairRank, tf: TfEval, costPct: number, kind: AssignedKind): StrategyInput {
  const futures = p.marketType === "PERPETUAL";
  // stops must outrun costs and tolerate a few adverse candles; TP ≈ 1.8× SL
  const stopLossPct = clamp(Math.max(1.5 * costPct, 2.5 * tf.movePct), 0.4, 4);
  const takeProfitPct = clamp(stopLossPct * 1.8, 0.6, 6);
  const trailingStopPct = clamp(2 * tf.movePct, 0.3, 2);
  const makerBetter =
    p.metrics.makerFeePct !== undefined && p.metrics.feePctPerSide !== undefined &&
    p.metrics.makerFeePct < p.metrics.feePctPerSide;
  const exchangeLabel = EXCHANGE_LABELS[p.exchange as keyof typeof EXCHANGE_LABELS] ?? p.exchange;

  return {
    name: `${KIND_NAME[kind]} ${p.symbol}`,
    description:
      `ساخته‌شده خودکار از اسکالپ اسکنر — امتیاز ${p.score?.toFixed(0) ?? "—"}/۱۰۰ · ${exchangeLabel}` +
      ` · حرکت میانگین کندل ${tf.movePct.toFixed(2)}٪ (${tf.tf}) · هزینه رفت‌وبرگشت ${costPct.toFixed(2)}٪`,
    kind,
    symbol: p.symbol,
    exchange: p.exchange,
    timeframe: tf.tf,
    buyThreshold: 0.35,
    sellThreshold: -0.35,
    riskPerTradePct: 1,
    stopLossPct: Math.round(stopLossPct * 100) / 100,
    takeProfitPct: Math.round(takeProfitPct * 100) / 100,
    trailingStop: true,
    trailingStopPct: Math.round(trailingStopPct * 100) / 100,
    maxPositionPct: 100,
    orderType: makerBetter ? "LIMIT" : "MARKET",
    market: futures ? "FUTURES" : "SPOT",
    ...(futures ? { leverage: FUTURES_LEVERAGE } : {}),
    indicators: kind === "SIGNAL" ? defaultIndicators() : [],
    // symbolic engines run with default params + self-learning enabled
    ...(kind === "ATM_SME" ? { atmSme: {}, smart: true } : {}),
    ...(kind === "RMM_BSE" ? { rmmBse: {}, smart: true } : {}),
  };
}

export async function autoGenerateStrategies(
  userId: string,
  opts: { count?: number; mode?: AutoGenMode } = {},
): Promise<AutoGenerateResult> {
  const count = clamp(Math.trunc(opts.count ?? 5), 1, 10);
  const mode: AutoGenMode = opts.mode ?? "SCALP";

  const result = await rankPairs({});
  const ranked = result.pairs.filter((p) => p.status === "RANKED" && p.score !== null);
  if (ranked.length === 0) {
    throw new AppError("INSUFFICIENT_DATA", 422, { reason: "no ranked pairs from scanner" });
  }

  // dedupe against the user's existing strategies (latest version symbol+exchange)
  const existing = await prisma.strategy.findMany({
    where: { userId, status: { not: "DELETED" } },
    select: {
      versions: {
        orderBy: { versionNumber: "desc" },
        take: 1,
        select: { symbol: true, config: true },
      },
    },
  });
  const taken = new Set(
    existing.flatMap((s) => {
      const v = s.versions[0];
      if (!v) return [];
      const cfg = parseJson<{ exchange?: string }>(v.config, {});
      return [`${(cfg.exchange ?? "NOBITEX").toUpperCase()}:${v.symbol}`];
    }),
  );

  const skipped: { symbol: string; exchange: string; reason: string }[] = [];
  const seenBases = new Set<string>();
  let evaluated = 0;

  // phase 1 — pick winners: dedupe + diversify + timeframe evaluation
  const picked: { p: PairRank; tf: TfEval; costPct: number }[] = [];
  for (const p of ranked) {
    if (picked.length >= count || evaluated >= MAX_EVALUATED) break;
    const key = `${p.exchange}:${p.symbol}`;

    if (taken.has(key)) {
      skipped.push({ symbol: p.symbol, exchange: p.exchange, reason: "استراتژی روی این جفت از قبل وجود دارد" });
      continue;
    }
    // diversify — one strategy per base asset (BTC spot + BTC perp would overlap)
    const base = `${p.exchange}:${p.baseCurrency}`;
    if (seenBases.has(base)) {
      skipped.push({ symbol: p.symbol, exchange: p.exchange, reason: "دارایی پایه‌ی تکراری — برای تنوع رد شد" });
      continue;
    }

    evaluated++;
    try {
      const costPct =
        p.metrics.roundTripCostPct || (p.metrics.feePctPerSide || 0.35) * 2 || DEFAULT_COST_PCT;
      const tf = await evalTimeframes(p, costPct);
      if (!tf) {
        skipped.push({
          symbol: p.symbol, exchange: p.exchange,
          reason: "داده‌ی کندل کافی نیست یا حرکت کندل‌ها هزینه‌ی معامله را پوشش نمی‌دهد",
        });
        continue;
      }
      taken.add(key);
      seenBases.add(base);
      picked.push({ p, tf, costPct });
    } catch (e) {
      skipped.push({ symbol: p.symbol, exchange: p.exchange, reason: userMessage(e) });
    }
  }

  // phase 2 — assign engine kind. COMBINED: the most volatile pick runs the
  // ATM_SME momentum engine, the least volatile runs RMM_BSE channel breakout
  // (squeeze → expansion suits calm pairs), the rest stay SIGNAL.
  const kinds = new Map<PairRank, AssignedKind>(picked.map(({ p }) => [p, "SIGNAL"]));
  if (mode === "COMBINED" && picked.length >= 3) {
    const byVol = [...picked].sort(
      (a, b) => (b.p.metrics.volatilityPct ?? b.tf.movePct) - (a.p.metrics.volatilityPct ?? a.tf.movePct),
    );
    kinds.set(byVol[0].p, "ATM_SME");
    kinds.set(byVol[byVol.length - 1].p, "RMM_BSE");
  }

  // phase 3 — create strategies
  const created: AutoGeneratedStrategy[] = [];
  for (const { p, tf, costPct } of picked) {
    try {
      const kind = kinds.get(p) ?? "SIGNAL";
      const input = buildInput(p, tf, costPct, kind);
      const { strategy } = await createStrategy(userId, input, "AI");
      created.push({
        id: strategy.id, name: strategy.name, symbol: p.symbol,
        exchange: p.exchange, market: input.market ?? "SPOT",
        timeframe: tf.tf, kind, score: p.score,
      });
    } catch (e) {
      skipped.push({ symbol: p.symbol, exchange: p.exchange, reason: userMessage(e) });
    }
  }

  logger.info("auto-generate strategies", {
    module: "strategies", userId, mode, created: created.length, skipped: skipped.length,
    scanned: result.meta.totalPairs, ranked: ranked.length,
  });
  await logActivity({ userId, action: "AUTO_GENERATE_STRATEGIES", entityType: "strategy" });
  if (created.length > 0) {
    await notify({
      userId, type: "SYSTEM", severity: "SUCCESS",
      title: "ایجاد خودکار استراتژی",
      body: `${created.length} استراتژی اسکالپ بر اساس رتبه‌بندی اسکنر ساخته شد: ${created.map((c) => c.symbol).join("، ")}`,
      metadata: { strategyIds: created.map((c) => c.id) },
    });
  }

  return {
    created, skipped,
    scanned: result.meta.totalPairs,
    ranked: ranked.length,
  };
}
